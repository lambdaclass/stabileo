export const strings = { en, es, pt, de, fr, tr, hu, zh };
export type Locale = keyof typeof strings;
export const pageLocale = (locale: string): Locale => (locale in strings ? (locale as Locale) : 'en');

const MESH = { regular: 'regular', trapezoidal: 'trapezoidal', parallelogram: 'parallelogram' } as const;

export function caseLabel(id: string, s: Strings): string {
  const frame = /^frame-(shear|moment)-(\d+)-(\w+)$/.exec(id);
  if (frame) {
    const n = Number(frame[2]);
    return `${s.frameAdaptation} · ${s[frame[1] as 'shear' | 'moment']} · ${n === 1 ? s.oneElement : s.manyElements.replace('{n}', String(n))} · ${frame[3]}`;
  }
  const shell = /^(mitc4|solid)-(regular|trapezoidal|parallelogram)-(out|in)$/.exec(id);
  if (shell) return `${shell[1] === 'mitc4' ? 'MITC4' : 'SHB8'} · ${s[MESH[shell[2] as keyof typeof MESH]]} · ${shell[3] === 'out' ? s.outOfPlane : s.inPlane}`;
  if (id === 'discretization_error::mitc9_curved_benchmarks_at_16x16') return s.mitc9Convergence;
  const named = s[id as keyof Strings];
  if (named === undefined) throw new Error(`No label for benchmark ${id}`);
  return named;
}

export function nativeReason(id: string, s: Strings): string {
  if (id.startsWith('solid-')) return s.reasonSolid;
  if (id.startsWith('discretization_error::')) return s.reasonMitc9;
  if (id === 'element_rigid_body_modes') return s.reasonElement;
  if (id.endsWith('_patch_test_distorted')) return s.reasonPatch;
  throw new Error(`No reason for native-only benchmark ${id}`);
}

/** Translated names of the published comparison rows, by row id. */
export function comparisonNames(s: Strings): Record<string, string> {
  const beam = (shape: 'regular' | 'trapezoidal' | 'parallelogram', load: 'out' | 'in') => `${s.straightBeam} · ${s[shape]} · ${load === 'out' ? s.outOfPlane : s.inPlane}`;
  return {
    'straight-regular-out': beam('regular', 'out'),
    'straight-regular-in': beam('regular', 'in'),
    'straight-trapezoidal-out': beam('trapezoidal', 'out'),
    'straight-parallelogram-out': beam('parallelogram', 'out'),
    'scordelis-lo-16': s.roofRow,
  };
}
