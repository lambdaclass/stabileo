export function caseLabel(id: string, s: typeof strings.en): string {
  const parts = id.split('-');
  if (parts[0] === 'frame') return `${s.frame} · ${parts[1] === 'shear' ? s.shear : s.moment} · ${parts[2]} ${s.elements} · ${parts[3]}`;
  const mesh = parts[1] as 'regular' | 'trapezoidal' | 'parallelogram';
  return `MITC4 · ${s[mesh]} · ${parts[2] === 'out' ? s.out : s.inside}`;
}
