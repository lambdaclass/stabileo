export function tm(key: string, params?: Record<string, string | number>): string {
  const raw = t(key);
  return params ? raw.replace(/\{(\w+)\}/g, (m, name) => (params[name] === undefined ? m : String(params[name]))) : raw;
}

export function formatter(digits = 2): (v: number) => string {
  const f = new Intl.NumberFormat(i18n.locale, { minimumFractionDigits: digits, maximumFractionDigits: digits });
  return (v: number) => f.format(Math.abs(v) < 0.5 * 10 ** -digits ? 0 : v);
}
