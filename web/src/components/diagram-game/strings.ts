export const gameStrings: Record<string, Record<Key, string>> = { en, es, pt, de, fr, tr, hu, it, zh };

export function tg(key: Key | `${Key}`, vars: Record<string, string | number> = {}): string {
  const table = gameStrings[publicI18n.locale] ?? en;
  const text = (table as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** The explanation for a wrong option, with the deflected-shape wording where one exists. */
export function tagText(tag: string, kind: string, from?: string): string {
  const specific = tag === 'wrongKind' && from ? `tag.wrongKind.${from}` : `tag.${tag}.${kind}`;
  return specific in en ? tg(specific as Key) : tg(`tag.${tag}` as Key);
}

/** Splits a question at its one bracketed term, the diagram's name, which the page draws in that diagram's colour. */
export function marked(text: string): { before: string; term: string; after: string } {
  const m = /^(.*?)\[(.+?)\](.*)$/s.exec(text);
  return m ? { before: m[1]!, term: m[2]!, after: m[3]! } : { before: text, term: '', after: '' };
}
