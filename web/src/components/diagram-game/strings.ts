export const gameStrings: Record<string, Record<Key, string>> = { en, es, pt, de, fr, tr };

export function tg(key: Key | `${Key}`, vars: Record<string, string | number> = {}): string {
  const table = gameStrings[publicI18n.locale] ?? en;
  const text = (table as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** The explanation for a wrong option, with the deflected-shape wording where one exists. */
export function tagText(tag: string, kind: string): string {
  const specific = `tag.${tag}.${kind}`;
  return specific in en ? tg(specific as Key) : tg(`tag.${tag}` as Key);
}
