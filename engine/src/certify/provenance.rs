//! Provenance of certificate bundles: what was solved, by which engine, and which
//! certificates the bundle carries. See "Provenance" under "Independent checking:
//! certificate bundles" in `docs/verification/CERTIFY.md`.
//!
//! The solver input is identified by the SHA-256 of its *canonical JSON*: the input
//! as the engine parsed it, serialized by `serde_json` with object keys sorted and no
//! whitespace (`canonical_json`). Sample bundles ship that exact text next to the
//! bundle, and `verify/scripts/check-bundles.sh` checks the hash.

use serde::{Deserialize, Serialize};

/// Where a bundle came from (`provenance` in every bundle format that has one).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Provenance {
    /// Lowercase hex SHA-256 of `canonical_json(input)`.
    pub input_sha256: String,
    /// The input type (`SolverInput3D`, `PlasticInput`, `MultiCaseInput`, …).
    pub input_kind: String,
    /// `CARGO_PKG_VERSION` of the engine.
    pub engine_version: String,
    /// Git commit the engine was built from (`unknown` if not available at build time).
    pub engine_commit: String,
    /// The certificate kinds the bundle carries.
    pub kinds: Vec<String>,
}

impl Provenance {
    pub fn new<T: Serialize>(input: &T, input_kind: &str, kinds: &[&str]) -> Result<Self, String> {
        Ok(Provenance {
            input_sha256: sha256_hex(canonical_json(input)?.as_bytes()),
            input_kind: input_kind.into(),
            engine_version: env!("CARGO_PKG_VERSION").into(),
            engine_commit: env!("STABILEO_ENGINE_COMMIT").into(),
            kinds: kinds.iter().map(|k| k.to_string()).collect(),
        })
    }
}

/// The canonical JSON text of a solver input: `serde_json` serialization through
/// `serde_json::Value` (whose maps are sorted by key), compact.
pub fn canonical_json<T: Serialize>(input: &T) -> Result<String, String> {
    let v = serde_json::to_value(input).map_err(|e| format!("input does not serialize: {e}"))?;
    serde_json::to_string(&v).map_err(|e| format!("input does not serialize: {e}"))
}

