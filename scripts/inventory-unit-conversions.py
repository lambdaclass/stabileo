#!/usr/bin/env python3
"""Reproduce the unit migration's lexical conversion-site audit (not a type proof)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PATTERNS = {
    'display boundary': r'\b(?:toDisplay|fromDisplay|elasticFromDisplay|elasticToDisplay|unitQ|toQ|unitLabel)\s*\(',
    'explicit scale': r'(?:\*|/)\s*(?:1_?000(?:_?000)?(?:\.0)?|100(?:\.0)?|10(?:\.0)?|1e[+-]?[2369]|1e[+-]?12|9\.8(?:1|0665)|25\.4|0\.0254|0\.3048|180(?:\.0)?)\b|\b(?:1_?000(?:_?000)?(?:\.0)?|1e[+-]?[2369]|1e[+-]?12)\s*[*/]',
    'named conversion': r'\b(?:[A-Za-z_]*(?:[Tt]o[Mm]et[er]|[Tt]o[Mm][Mm]|[Tt]o[Cc][Mm]|[Tt]o[Kk][Nn]|[Tt]o[Nn]ewton|[Tt]o[Rr]ad|[Tt]o[Dd]eg)[A-Za-z_]*|to_internal|in_mpa|in_kn_per_m2|from_mpa|from_kn_per_m2)\s*\(',
    'unit declaration/factor': r'\b(?:SI_FACTORS|SIMM_FACTORS|MKS_FACTORS|FACTORS|UNIT_SCALE|MPa|kg/m³|kN/m³|kgf/cm|ksi|pcf)\b|(?:MPa|kN|mm|cm|kg|tonne).*(?:→|convert)',
}
print('# Unit conversion audit index\n')
print('Generated by `python3 scripts/inventory-unit-conversions.py`. Production sources only;')
print('tests, fixtures and generated WASM are excluded. Line numbers refer to this worktree.\n')
print('Every match is listed, grouped by file and rule. Explicit-scale hits include numerical')
print('conditioning constants and tolerances: they are candidates, **not instructions to convert**.')
print('This lexical index cannot prove that arbitrary arithmetic contains no other conversion;')
print('the semantic survey and migration checklist are in [units-in-types.md](units-in-types.md).\n')
print('| File | Rule | Lines |\n| --- | --- | --- |')
count = 0
for tree in ['engine/src', 'web/src/lib', 'web/src/components']:
    for p in sorted((ROOT / tree).rglob('*')):
        if not p.is_file() or p.suffix not in {'.rs', '.ts', '.svelte'}: continue
        if any(x in p.parts for x in ['__tests__', 'wasm', 'fixtures']) or '.test.' in p.name or '.typecheck.' in p.name: continue
        content = p.read_text().splitlines()
        # Rust in-file unit tests are not production conversions.
        if p.suffix == '.rs':
            cut = next((i for i, s in enumerate(content) if s.strip() == '#[cfg(test)]'), len(content))
            content = content[:cut]
        for label, pattern in PATTERNS.items():
            lines = [str(i) for i, line in enumerate(content, 1) if re.search(pattern, line)]
            if lines:
                count += len(lines)
                print(f'| `{p.relative_to(ROOT)}` | {label} | {", ".join(lines)} |')
print(f'\n{count} rule matches (a line may match several rules).')
